#!/usr/bin/env python3
"""Refresh AWS Step Functions spec snapshots under aws-spec/.

Reads aws-spec/sources.json. Writes only files inside aws-spec/. Leaves
docs/spec.md alone. A second run with the same upstream bytes changes nothing.

GitHub Actions cannot subscribe to RSS. The workflow polls this script on a
schedule and opens a pull request when a snapshot changes.
"""

from __future__ import annotations

import email.utils
import hashlib
import html
import json
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
import xml.etree.ElementTree as ET
from datetime import timezone
from pathlib import Path

UA = "sfn-local-aws-spec-sync/1.0"
NOTE = (
    "Generated by aws-spec/tools/sync_aws_spec.py from public AWS sources. "
    "This is an AWS Step Functions snapshot. The local runner design stays in docs/spec.md."
)
ROOT = Path(__file__).resolve().parents[1]
SOURCES_PATH = ROOT / "sources.json"

DOCS_HINT = re.compile(
    r"documentation-only|document structure|fixed code sample|typo|"
    r"re-organized|reorganized the|simplified and re-organized",
    re.IGNORECASE,
)
BEHAVIOR_HINT = re.compile(
    r"jsonata|querylanguage|query language|\bvariables?\b|intrinsic|"
    r"states language|distributed map|itemreader|itemselector|itembatcher|"
    r"resultwriter|teststate|test state|redrive|validatestatemachine|"
    r"payload|service quota|error handling|https endpoint|waitfortasktoken|"
    r"\.sync|\bactivity\b|state machine definition|\bassign\b|\$states",
    re.IGNORECASE,
)


def fetch(url: str) -> bytes:
    last_error: Exception | None = None
    for attempt in range(3):
        request = urllib.request.Request(url, headers={"User-Agent": UA, "Accept": "*/*"})
        try:
            with urllib.request.urlopen(request, timeout=60) as response:
                body = response.read()
            if not body:
                raise RuntimeError("empty body")
            return body
        except (urllib.error.URLError, TimeoutError, RuntimeError) as error:
            last_error = error
            if attempt < 2:
                time.sleep(1.5 * (attempt + 1))
    raise SystemExit(f"fetch failed for {url}: {last_error}")


def decode_text(body: bytes) -> str:
    return body.decode("utf-8-sig")


def dump_json(payload: object) -> bytes:
    return (json.dumps(payload, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def write_if_changed(relative: str, body: bytes) -> bool:
    if relative.startswith("/") or ".." in Path(relative).parts:
        raise SystemExit(f"refusing to write outside aws-spec: {relative}")
    path = ROOT / relative
    if not path.resolve().is_relative_to(ROOT.resolve()):
        raise SystemExit(f"refusing to write outside aws-spec: {relative}")
    if path.is_file() and path.read_bytes() == body:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(body)
    return True


def load_json(relative: str) -> object | None:
    path = ROOT / relative
    if not path.is_file():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def sha256(body: bytes) -> str:
    return hashlib.sha256(body).hexdigest()


def clean_cell(value: str) -> str:
    text = value.replace("<br />", "\n").replace("<br/>", "\n").replace("<br>", "\n")
    text = html.unescape(text)
    text = re.sub(r"[ \t]+\n", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def markdown_tables(text: str) -> list[tuple[list[str], list[list[str]]]]:
    """Return every GitHub-style table. A blank line closes the current table."""
    tables: list[tuple[list[str], list[list[str]]]] = []
    header: list[str] | None = None
    rows: list[list[str]] = []

    def close() -> None:
        nonlocal header, rows
        if header is not None and rows:
            tables.append((header, rows))
        header = None
        rows = []

    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line.startswith("|"):
            close()
            continue
        cells = [cell.strip() for cell in line.strip("|").split("|")]
        if cells and all(cell and set(cell) <= set("-: ") for cell in cells):
            continue
        if header is None:
            header = cells
            continue
        if len(cells) < len(header):
            raise SystemExit(f"short table row: {line[:120]}")
        if len(cells) > len(header):
            head_count = len(header)
            cells = cells[: head_count - 1] + ["|".join(cells[head_count - 1 :])]
        rows.append([clean_cell(cell) for cell in cells])
    close()
    return tables


def parse_markdown_table(text: str, expected_header: list[str]) -> list[dict[str, str]]:
    tables = markdown_tables(text)
    if len(tables) != 1:
        raise SystemExit(f"expected 1 table for {expected_header}, found {len(tables)}")
    header, rows = tables[0]
    got = [cell.lower() for cell in header]
    want = [cell.lower() for cell in expected_header]
    if got != want:
        raise SystemExit(f"unexpected table header {got}, want {want}")
    if not rows:
        raise SystemExit(f"no data rows for header {expected_header}")
    return [dict(zip(expected_header, row, strict=True)) for row in rows]


def local_runtime_hint(change: str, text: str) -> str:
    if DOCS_HINT.search(change) or DOCS_HINT.search(text[:160]):
        return "docs"
    if BEHAVIOR_HINT.search(f"{change}\n{text}"):
        return "behavior"
    return "unclassified"


def markdown_link(cell: str, base_url: str) -> tuple[str, str]:
    match = re.search(r"\[([^\]]+)\]\(([^)]+)\)", cell)
    if match is None:
        return clean_cell(cell), ""
    return clean_cell(match.group(1)), urllib.parse.urljoin(base_url, match.group(2).strip())


def parse_rss(body: bytes, source_url: str) -> dict[str, object]:
    root = ET.fromstring(body)
    channel = root.find("channel")
    if channel is None:
        raise SystemExit("RSS feed has no channel")
    items: list[dict[str, object]] = []
    seen: set[str] = set()
    for item in channel.findall("item"):
        guid = (item.findtext("guid") or item.findtext("link") or "").strip()
        title = clean_cell(item.findtext("title") or "")
        link = (item.findtext("link") or "").strip()
        description = clean_cell(item.findtext("description") or "")
        published_raw = (item.findtext("pubDate") or "").strip()
        if not guid or not title:
            raise SystemExit("RSS item is missing guid or title")
        if guid in seen:
            raise SystemExit(f"duplicate RSS guid: {guid}")
        seen.add(guid)
        published = published_raw
        sort_key = published_raw
        parsed = email.utils.parsedate_to_datetime(published_raw) if published_raw else None
        if parsed is not None:
            published = parsed.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
            sort_key = published
        items.append(
            {
                "guid": guid,
                "title": title,
                "link": link,
                "published": published,
                "description": description,
                "local_runtime_hint": local_runtime_hint("", f"{title}\n{description}"),
                "_sort": sort_key,
            }
        )
    if not items:
        raise SystemExit("RSS feed has no items")
    items.sort(key=lambda row: (str(row["_sort"]), str(row["guid"])), reverse=True)
    for row in items:
        del row["_sort"]
    title = clean_cell(channel.findtext("title") or "")
    return {
        "_note": NOTE,
        "source_url": source_url,
        "channel_title": title,
        "hint_note": (
            "local_runtime_hint is a keyword guess added by the sync script. "
            "AWS does not publish that label. behavior means a person should read the row "
            "before changing a local interpreter. docs means the row looks like a documentation edit."
        ),
        "items": items,
    }


def parse_document_history(text: str, source_url: str) -> dict[str, object]:
    rows = parse_markdown_table(text, ["Change", "Description", "Date changed"])
    items = [
        {
            "change": row["Change"],
            "date": row["Date changed"],
            "description": row["Description"],
            "local_runtime_hint": local_runtime_hint(row["Change"], row["Description"]),
        }
        for row in rows
    ]
    return {"_note": NOTE, "source_url": source_url, "rows": items}


def parse_recent_launches(text: str, source_url: str) -> dict[str, object]:
    rows = parse_markdown_table(text, ["Launch date", "Feature description"])
    items = []
    for row in rows:
        title, url = markdown_link(row["Feature description"], source_url)
        items.append(
            {
                "date": row["Launch date"],
                "title": title,
                "url": url,
                "local_runtime_hint": local_runtime_hint("", title),
            }
        )
    return {"_note": NOTE, "source_url": source_url, "launches": items}


SDK_PROSE = re.compile(
    r"(\d+\s+new\b|API actions|launched with|plus over|service integrations\b)",
    re.IGNORECASE,
)


def sdk_entries(rows: list[list[str]]) -> list[dict[str, object]]:
    entries = []
    for date, services_cell in rows:
        parts = [part.strip() for part in services_cell.split(",") if part.strip()]
        if not parts:
            raise SystemExit(f"SDK integration row is empty: {date}")
        if any(SDK_PROSE.search(part) for part in parts):
            entries.append({"date": date, "summary": services_cell})
        else:
            entries.append({"date": date, "services": parts})
    return entries


def parse_sdk_integrations(text: str, source_url: str) -> dict[str, object]:
    tables = markdown_tables(text)
    added: list[list[str]] | None = None
    removed: list[list[str]] | None = None
    for header, rows in tables:
        got = [cell.lower() for cell in header]
        if got == ["date", "services added"]:
            added = rows
        elif got == ["date", "services deprecated"]:
            removed = rows
        else:
            raise SystemExit(f"unexpected SDK integration table header {got}")
    if not added:
        raise SystemExit("SDK integration page is missing the services-added table")
    if not removed:
        raise SystemExit("SDK integration page is missing the services-deprecated table")
    return {
        "_note": NOTE,
        "source_url": source_url,
        "added": sdk_entries(added),
        "deprecated": sdk_entries(removed),
    }


def shape_summary(shapes: dict[str, dict], target: str) -> dict[str, object]:
    shape = shapes[target]
    kind = shape["type"]
    name = target.split("#", 1)[-1]
    summary: dict[str, object] = {"name": name, "type": kind}
    values: list[object] = []
    enum_trait = shape.get("traits", {}).get("smithy.api#enum")
    if isinstance(enum_trait, list):
        values = [entry.get("value") or entry.get("name") for entry in enum_trait]
    elif kind == "enum":
        for member_name, member in shape.get("members", {}).items():
            member_traits = member.get("traits", {})
            if "smithy.api#enumValue" in member_traits:
                values.append(member_traits["smithy.api#enumValue"])
            else:
                values.append(member_name)
    if values:
        summary["enum"] = values
    if kind == "list":
        summary["member"] = shape["member"]["target"].split("#", 1)[-1]
    elif kind == "map":
        summary["key"] = shape["key"]["target"].split("#", 1)[-1]
        summary["value"] = shape["value"]["target"].split("#", 1)[-1]
    return summary


def member_summary(shapes: dict[str, dict], name: str, member: dict) -> dict[str, object]:
    traits = member.get("traits", {})
    entry: dict[str, object] = {
        "name": name,
        "target": member["target"].split("#", 1)[-1],
        "required": "smithy.api#required" in traits,
    }
    entry.update(shape_summary(shapes, member["target"]))
    entry["name"] = name
    if "smithy.api#default" in traits:
        default = traits["smithy.api#default"]
        if isinstance(default, dict) and set(default) == {"value"}:
            entry["default"] = default["value"]
        else:
            entry["default"] = default
    return entry


def structure_members(shapes: dict[str, dict], target: str | None) -> list[dict[str, object]]:
    if target is None:
        return []
    shape = shapes[target]
    if shape["type"] != "structure":
        raise SystemExit(f"expected structure, got {shape['type']} for {target}")
    members = shape.get("members", {})
    return [member_summary(shapes, name, member) for name, member in members.items()]


def operations_summary(model: dict, source_name: str) -> dict[str, object]:
    shapes = model["shapes"]
    service_id = "com.amazonaws.sfn#AWSStepFunctions"
    service = shapes.get(service_id)
    if service is None or service.get("type") != "service":
        raise SystemExit("Smithy model is missing com.amazonaws.sfn#AWSStepFunctions")
    traits = service.get("traits", {})
    if "aws.protocols#awsJson1_0" not in traits:
        raise SystemExit("Smithy service is missing aws.protocols#awsJson1_0")
    api_service = traits.get("aws.api#service", {})
    sigv4 = traits.get("aws.auth#sigv4", {})
    operations = []
    for ref in service.get("operations", []):
        target = ref["target"]
        operation = shapes[target]
        if operation.get("type") != "operation":
            raise SystemExit(f"{target} is not an operation")
        errors = []
        for error_ref in operation.get("errors", []):
            error_target = error_ref["target"]
            error_shape = shapes[error_target]
            error_traits = error_shape.get("traits", {})
            errors.append(
                {
                    "name": error_target.split("#", 1)[-1],
                    "fault": error_traits.get("smithy.api#error"),
                    "http_status": error_traits.get("smithy.api#httpError"),
                }
            )
        operations.append(
            {
                "name": target.split("#", 1)[-1],
                "idempotent": "smithy.api#idempotent" in operation.get("traits", {}),
                "input": structure_members(shapes, (operation.get("input") or {}).get("target")),
                "output": structure_members(shapes, (operation.get("output") or {}).get("target")),
                "errors": errors,
            }
        )
    operations.sort(key=lambda item: item["name"])
    if len(operations) < 20:
        raise SystemExit(f"expected the States API to list its operations, got {len(operations)}")
    return {
        "_note": (
            "Generated from the vendored Smithy snapshot. Documentation strings are omitted. "
            "The local runner design stays in docs/spec.md."
        ),
        "source": source_name,
        "service": service_id,
        "version": service.get("version"),
        "protocol": "aws.protocols#awsJson1_0",
        "target_prefix": service_id.split("#", 1)[-1],
        "endpoint_prefix": api_service.get("endpointPrefix"),
        "sdk_id": api_service.get("sdkId"),
        "arn_namespace": api_service.get("arnNamespace"),
        "sigv4_name": sigv4.get("name"),
        "operations": operations,
    }


def new_release_lines(old: object | None, new: dict[str, object]) -> list[str]:
    old_guids: set[str] = set()
    if isinstance(old, dict):
        for item in old.get("items", []):
            if isinstance(item, dict) and "guid" in item:
                old_guids.add(str(item["guid"]))
    lines = []
    for item in new["items"]:
        if not isinstance(item, dict):
            continue
        if str(item["guid"]) in old_guids:
            continue
        lines.append(f"  + {item['published']} {item['title']}")
    return lines


def new_history_lines(old: object | None, new: dict[str, object]) -> list[str]:
    old_rows: set[tuple[str, str, str]] = set()
    if isinstance(old, dict):
        for row in old.get("rows", []):
            if isinstance(row, dict):
                old_rows.add((str(row.get("change")), str(row.get("date")), str(row.get("description"))))
    lines = []
    for row in new["rows"]:
        if not isinstance(row, dict):
            continue
        key = (str(row["change"]), str(row["date"]), str(row["description"]))
        if key in old_rows:
            continue
        first_line = str(row["description"]).split("\n", 1)[0]
        if len(first_line) > 140:
            first_line = first_line[:137] + "..."
        lines.append(f"  + {row['date']} [{row['change']}] {first_line}")
    return lines


def changed_pages(old: object | None, new: dict[str, object]) -> list[str]:
    old_hashes: dict[str, str] = {}
    if isinstance(old, dict):
        for page in old.get("pages", []):
            if isinstance(page, dict):
                old_hashes[str(page.get("id"))] = str(page.get("sha256"))
    lines = []
    for page in new["pages"]:
        if not isinstance(page, dict):
            continue
        page_id = str(page["id"])
        digest = str(page["sha256"])
        previous = old_hashes.get(page_id)
        if previous is None:
            lines.append(f"  + {page_id}")
        elif previous != digest:
            lines.append(f"  ~ {page_id}")
    return lines


def main() -> None:
    sources = json.loads(SOURCES_PATH.read_text(encoding="utf-8"))
    summary: list[str] = []

    feed = sources["feed"]
    feed_body = fetch(feed["url"])
    release_notes = parse_rss(feed_body, feed["url"])
    old_release = load_json("release-notes.json")
    if write_if_changed("release-notes.json", dump_json(release_notes)):
        added = new_release_lines(old_release, release_notes)
        summary.append(f"changed: release-notes.json ({len(release_notes['items'])} items)")
        summary.extend(added[:20])
        if len(added) > 20:
            summary.append(f"  + {len(added) - 20} more")

    table_parsers = {
        "document-history": parse_document_history,
        "recent-launches": parse_recent_launches,
        "sdk-integrations": parse_sdk_integrations,
    }
    table_outputs = {
        "document-history": "document-history.json",
        "recent-launches": "recent-launches.json",
        "sdk-integrations": "sdk-integrations.json",
    }
    for table in sources["tables"]:
        kind = table["kind"]
        parser = table_parsers[kind]
        text = decode_text(fetch(table["url"]))
        parsed = parser(text, table["url"])
        output = table_outputs[kind]
        old = load_json(output)
        if write_if_changed(output, dump_json(parsed)):
            summary.append(f"changed: {output}")
            if kind == "document-history":
                added = new_history_lines(old, parsed)
                summary.extend(added[:20])
                if len(added) > 20:
                    summary.append(f"  + {len(added) - 20} more")

    model_info = sources["model"]
    model_bytes = fetch(model_info["url"])
    try:
        model = json.loads(model_bytes)
    except json.JSONDecodeError as error:
        raise SystemExit(f"States API model is not JSON: {error}") from error
    model_output = model_info["output"]
    if write_if_changed(model_output, model_bytes):
        summary.append(f"changed: {model_output}")
    operations = operations_summary(model, model_output)
    if write_if_changed("states-api/operations.json", dump_json(operations)):
        summary.append(
            f"changed: states-api/operations.json ({len(operations['operations'])} operations)"
        )

    asl_info = sources["asl"]
    asl_bytes = fetch(asl_info["url"])
    asl_text = asl_bytes.decode("utf-8", "replace")
    if "Amazon States Language" not in asl_text or "Permission is hereby granted" not in asl_text:
        raise SystemExit("ASL fetch did not look like the States Language specification")
    if "You may not modify" not in asl_text:
        raise SystemExit("ASL fetch is missing the specification's no-modify notice")
    if write_if_changed(asl_info["output"], asl_bytes):
        summary.append(f"changed: {asl_info['output']}")

    witness_pages = []
    for witness in sources["witnesses"]:
        body = fetch(witness["url"])
        witness_pages.append(
            {
                "id": witness["id"],
                "url": witness["url"],
                "why": witness["why"],
                "sha256": sha256(body),
                "bytes": len(body),
            }
        )
    witness_doc = {"_note": NOTE, "witnesses": witness_pages}
    old_witness = load_json("witnesses.json")
    if write_if_changed("witnesses.json", dump_json(witness_doc)):
        summary.append("changed: witnesses.json")
        if isinstance(old_witness, dict):
            old_by_id = {
                str(item.get("id")): str(item.get("sha256"))
                for item in old_witness.get("witnesses", [])
                if isinstance(item, dict)
            }
            for item in witness_pages:
                previous = old_by_id.get(item["id"])
                if previous and previous != item["sha256"]:
                    summary.append(f"  ~ {item['id']}")

    pages = []
    for page in sources["pages"]:
        body = fetch(page["url"])
        pages.append(
            {
                "id": page["id"],
                "url": page["url"],
                "why": page["why"],
                "sha256": sha256(body),
                "bytes": len(body),
            }
        )
    page_doc = {
        "_note": (
            "SHA-256 of AWS developer-guide pages that define Step Functions behavior. "
            "The page text is not stored. Open the URL when a hash changes. "
            "The local runner design stays in docs/spec.md."
        ),
        "pages": pages,
    }
    old_pages = load_json("page-watch.json")
    if write_if_changed("page-watch.json", dump_json(page_doc)):
        summary.append("changed: page-watch.json")
        summary.extend(changed_pages(old_pages, page_doc)[:30])

    if not summary:
        print("no file changes")
        return
    print("\n".join(summary))


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        sys.exit(130)
