// Command genops writes internal/invoke/operations.toml: every operation of
// every AWS SDK for Go v2 client internal/sdk runs, and whether it runs.
//
// The list comes from the client's methods, so an SDK upgrade that adds an
// operation adds a row. A table entry that names no method is an error.
package main

import (
	"context"
	"flag"
	"fmt"
	"os"
	"reflect"
	"sort"
	"strings"
	"unicode"
	"unicode/utf8"

	"github.com/catdevman/sfn-local/internal/sdk"
)

type operation struct {
	service, action, status string
	opaque                  []string
}

func main() {
	out := flag.String("out", "", "operations.toml to write")
	flag.Parse()
	if *out == "" {
		fmt.Fprintln(os.Stderr, "genops: -out is required")
		os.Exit(2)
	}
	ops, err := inventory()
	if err != nil {
		fmt.Fprintln(os.Stderr, "genops:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, []byte(render(ops)), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "genops:", err)
		os.Exit(1)
	}
}

func inventory() ([]operation, error) {
	var all []operation
	for _, id := range sdk.Services() {
		handled := map[string]bool{}
		for _, a := range sdk.Actions(id) {
			handled[a] = true
		}
		methods := clientOperations(reflect.TypeOf(sdk.Client(id)))
		for _, m := range methods {
			action := lowerFirst(m.Name)
			op := operation{service: id, action: action, status: "unsupported"}
			op.opaque = append(prefixed("input.", sdk.Opaque(m.Type.In(2).Elem())), prefixed("output.", sdk.Opaque(m.Type.Out(0).Elem()))...)
			if handled[action] {
				op.status = "implemented"
				if len(op.opaque) > 0 {
					op.status = "codec"
				}
				delete(handled, action)
			}
			all = append(all, op)
		}
		if len(handled) > 0 {
			var extra []string
			for a := range handled {
				extra = append(extra, a)
			}
			sort.Strings(extra)
			return nil, fmt.Errorf("%s actions with no client method: %s", id, strings.Join(extra, ", "))
		}
	}
	return all, nil
}

var (
	ctxType = reflect.TypeFor[context.Context]()
	errType = reflect.TypeFor[error]()
)

// clientOperations returns methods shaped like
// func(context.Context, *XInput, ...func(*Options)) (*XOutput, error).
func clientOperations(t reflect.Type) []reflect.Method {
	var out []reflect.Method
	for i := 0; i < t.NumMethod(); i++ {
		m := t.Method(i)
		ft := m.Type
		if ft.NumIn() != 4 || !ft.IsVariadic() || ft.In(1) != ctxType || ft.NumOut() != 2 || ft.Out(1) != errType {
			continue
		}
		in, outT := ft.In(2), ft.Out(0)
		if in.Kind() != reflect.Pointer || in.Elem().Name() != m.Name+"Input" {
			continue
		}
		if outT.Kind() != reflect.Pointer || outT.Elem().Name() != m.Name+"Output" {
			continue
		}
		out = append(out, m)
	}
	sort.Slice(out, func(i, j int) bool { return lowerFirst(out[i].Name) < lowerFirst(out[j].Name) })
	return out
}

func render(ops []operation) string {
	var b strings.Builder
	b.WriteString("# Generated by cmd/genops. Do not edit.\n")
	b.WriteString("# Every operation of every AWS SDK for Go v2 client in internal/sdk.\n")
	b.WriteString("# implemented runs through op. codec runs through a hand-written handler.\n")
	b.WriteString("# unsupported has no handler. opaque lists members the codec cannot carry.\n")
	counts := map[string][2]int{}
	var ids []string
	for _, op := range ops {
		c, seen := counts[op.service]
		if !seen {
			ids = append(ids, op.service)
		}
		c[1]++
		if op.status != "unsupported" {
			c[0]++
		}
		counts[op.service] = c
	}
	for _, id := range ids {
		fmt.Fprintf(&b, "# %s: %d of %d operations run.\n", id, counts[id][0], counts[id][1])
	}
	for _, op := range ops {
		fmt.Fprintf(&b, "\n[[operation]]\nservice = %q\naction = %q\nstatus = %q\n", op.service, op.action, op.status)
		if len(op.opaque) > 0 {
			fmt.Fprintf(&b, "opaque = %q\n", strings.Join(op.opaque, ", "))
		}
	}
	return b.String()
}

func prefixed(p string, names []string) []string {
	out := make([]string, len(names))
	for i, n := range names {
		out[i] = p + n
	}
	return out
}

func lowerFirst(s string) string {
	r, n := utf8.DecodeRuneInString(s)
	return string(unicode.ToLower(r)) + s[n:]
}
