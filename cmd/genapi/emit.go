func emit(m *model, outDir, sourceName string) error {
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}
	g := &generator{m: m, source: sourceName, patterns: map[string]patternProgram{}}
	types, err := g.types()
	if err != nil {
		return err
	}
	ops, err := g.operations()
	if err != nil {
		return err
	}
	errs, err := g.errorsFile()
	if err != nil {
		return err
	}
	valid, err := g.validateFile()
	if err != nil {
		return err
	}
	surface, err := g.surface()
	if err != nil {
		return err
	}
	ts := strings.Replace(timestampSrc, "Code generated by cmd/genapi.", "Code generated by cmd/genapi from "+sourceName+".", 1)
	files := map[string]string{
		"types.go":      types,
		"timestamp.go":  ts,
		"operations.go": ops,
		"errors.go":     errs,
		"validate.go":   valid,
	}
	for name, src := range files {
		if err := writeGo(outDir, name, src); err != nil {
			return err
		}
	}
	return os.WriteFile(filepath.Join(outDir, "surface.gen.json"), surface, 0o644)
}

func writeGo(dir, name, src string) error {
	formatted, err := format.Source([]byte(src))
	if err != nil {
		path := filepath.Join(os.TempDir(), "genapi-"+name)
		_ = os.WriteFile(path, []byte(src), 0o644)
		return fmt.Errorf("%s: %w (unformatted source at %s)", name, err, path)
	}
	if !bytes.HasSuffix(formatted, []byte("\n")) {
		formatted = append(formatted, '\n')
	}
	return os.WriteFile(filepath.Join(dir, name), formatted, 0o644)
}

type generator struct {
	m        *model
	source   string
	patterns map[string]patternProgram
}

func (g *generator) header() string {
	return "// Code generated by cmd/genapi from " + g.source + ". DO NOT EDIT.\n\npackage gen\n\n"
}

func (g *generator) sorted(kind string) []*shape {
	var out []*shape
	for _, id := range g.m.Order {
		sh := g.m.Shapes[id]
		if sh.Kind == kind {
			out = append(out, sh)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

func (g *generator) valueType(id string) (string, error) {
	sh := g.m.shape(id)
	switch sh.Kind {
	case "string":
		return "string", nil
	case "boolean":
		return "bool", nil
	case "integer":
		return "int32", nil
	case "long":
		return "int64", nil
	case "float":
		return "float64", nil
	case "timestamp":
		return "Timestamp", nil
	case "enum", "structure", "list", "map":
		return sh.Name, nil
	default:
		return "", fmt.Errorf("unsupported shape kind %q for shape %s", sh.Kind, id)
	}
}

func (g *generator) types() (string, error) {
	var b strings.Builder
	b.WriteString(g.header())
	for _, sh := range g.sorted("enum") {
		if err := g.writeEnum(&b, sh); err != nil {
			return "", err
		}
	}
	for _, sh := range g.sorted("list") {
		elem, err := g.valueType(sh.ListOf.Target)
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "type %s []%s\n\n", sh.Name, elem)
	}
	for _, sh := range g.sorted("map") {
		key := "string"
		if g.m.shape(sh.MapKey.Target).Kind == "enum" {
			key = g.m.shape(sh.MapKey.Target).Name
		}
		val, err := g.valueType(sh.MapValue.Target)
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "type %s map[%s]%s\n\n", sh.Name, key, val)
	}
	for _, sh := range g.sorted("structure") {
		fmt.Fprintf(&b, "type %s struct {\n", sh.Name)
		for _, mem := range sh.Members {
			vt, err := g.valueType(mem.Target)
			if err != nil {
				return "", err
			}
			fmt.Fprintf(&b, "\t%s *%s `json:%q`\n", exportName(mem.Name), vt, mem.Name+",omitempty")
		}
		b.WriteString("}\n\n")
	}
	return b.String(), nil
}

func (g *generator) writeEnum(b *strings.Builder, sh *shape) error {
	fmt.Fprintf(b, "type %s string\n\n", sh.Name)
	fmt.Fprintf(b, "const (\n")
	seen := map[string]bool{}
	for i, mem := range sh.Members {
		val := sh.enumValues()[i]
		cn := sh.Name + mem.Name
		if seen[cn] {
			return fmt.Errorf("duplicate const %s", cn)
		}
		seen[cn] = true
		fmt.Fprintf(b, "\t%s %s = %q\n", cn, sh.Name, val)
	}
	b.WriteString(")\n\n")
	fmt.Fprintf(b, "func (e %s) Valid() bool {\n\tswitch e {\n\tcase ", sh.Name)
	for i, mem := range sh.Members {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "%s%s", sh.Name, mem.Name)
	}
	b.WriteString(":\n\t\treturn true\n\tdefault:\n\t\treturn false\n\t}\n}\n\n")
	fmt.Fprintf(b, "var %sValues = []string{", sh.Name)
	for i, val := range sh.enumValues() {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "%q", val)
	}
	b.WriteString("}\n\n")
	return nil
}

func (g *generator) operations() (string, error) {
	var b strings.Builder
	b.WriteString(g.header())
	b.WriteString(`import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"io"
)

`)
	fmt.Fprintf(&b, "const Protocol = %q\n\n", protocolTrait)
	fmt.Fprintf(&b, "const TargetPrefix = %q\n\n", g.m.Service.Name)
	fmt.Fprintf(&b, "const ServiceVersion = %q\n\n", g.m.Service.Version)
	b.WriteString(`// Operation is one modeled API operation.
type Operation struct {
	Name        string
	Target      string
	Input       string
	Output      string
	Errors      []string
	Idempotent  bool
	InputToken  string
	OutputToken string
	PageItems   string
	PageSize    string
}

// UnimplementedError is a plain Go error. The HTTP layer turns it into
// InternalFailure when a handler is called before it is written.
type UnimplementedError struct {
	Operation string
}

func (e *UnimplementedError) Error() string {
	return e.Operation + " is not implemented"
}

// Handlers is one method per modeled operation.
type Handlers interface {
`)
	ops := g.serviceOps()
	for _, op := range ops {
		in := g.m.shape(op.Input).Name
		out := g.m.shape(op.Output).Name
		fmt.Fprintf(&b, "\t%s(context.Context, *%s) (*%s, error)\n", op.Name, in, out)
	}
	b.WriteString("}\n\n// Unimplemented returns a plain error for every operation.\ntype Unimplemented struct{}\n\n")
	for _, op := range ops {
		in := g.m.shape(op.Input).Name
		out := g.m.shape(op.Output).Name
		fmt.Fprintf(&b, "func (Unimplemented) %s(context.Context, *%s) (*%s, error) {\n\treturn nil, &UnimplementedError{Operation: %q}\n}\n\n", op.Name, in, out, op.Name)
	}
	b.WriteString("var Operations = []Operation{\n")
	for _, op := range ops {
		g.writeOpLiteral(&b, op)
	}
	b.WriteString("}\n\nvar operationsByName = map[string]Operation{\n")
	for _, op := range ops {
		fmt.Fprintf(&b, "\t%q: Operations[%d],\n", op.Name, indexOf(ops, op.Name))
	}
	b.WriteString("}\n\nfunc OperationByName(name string) (Operation, bool) {\n\top, ok := operationsByName[name]\n\treturn op, ok\n}\n\n")
	// The composite literal above refers to Operations by index before the
	// slice exists at init time. A map literal cannot refer to Operations[i]
	// if Operations is a slice var being initialized... actually it can,
	// because Operations is a package-level var and the map is another var.
	// Initialization order: Operations first, then operationsByName. In Go,
	// dependent package vars are initialized in dependency order. The map
	// references Operations, so Operations is initialized first. Good.
	b.WriteString("func DecodeInput(name string, body []byte) (any, error) {\n\tif len(bytes.TrimSpace(body)) == 0 {\n\t\tbody = []byte(\"{}\")\n\t}\n\tvar dst any\n\tswitch name {\n")
	for _, op := range ops {
		in := g.m.shape(op.Input).Name
		fmt.Fprintf(&b, "\tcase %q:\n\t\tdst = &%s{}\n", op.Name, in)
	}
	b.WriteString("\tdefault:\n\t\treturn nil, fmt.Errorf(\"unknown operation %s\", name)\n\t}\n\tif err := unmarshalObject(body, dst); err != nil {\n\t\tmsg := \"1 validation error detected: the request body failed to satisfy constraint: \" + err.Error()\n\t\treturn nil, &ValidationException{Message: &msg}\n\t}\n\treturn dst, nil\n}\n\n")
	b.WriteString("func ValidateInput(name string, in any) error {\n\tswitch name {\n")
	for _, op := range ops {
		fmt.Fprintf(&b, "\tcase %q:\n\t\treturn in.(*%s).Validate()\n", op.Name, g.m.shape(op.Input).Name)
	}
	b.WriteString("\tdefault:\n\t\treturn fmt.Errorf(\"unknown operation %s\", name)\n\t}\n}\n\n")
	b.WriteString("func Call(ctx context.Context, name string, h Handlers, in any) (any, error) {\n\tswitch name {\n")
	for _, op := range ops {
		in := g.m.shape(op.Input).Name
		fmt.Fprintf(&b, "\tcase %q:\n\t\treturn h.%s(ctx, in.(*%s))\n", op.Name, op.Name, in)
	}
	b.WriteString("\tdefault:\n\t\treturn nil, fmt.Errorf(\"unknown operation %s\", name)\n\t}\n}\n\n")
	b.WriteString(`func unmarshalObject(body []byte, dst any) error {
	trim := bytes.TrimSpace(body)
	if len(trim) == 0 || trim[0] != '{' {
		return fmt.Errorf("body must be a JSON object")
	}
	dec := json.NewDecoder(bytes.NewReader(trim))
	if err := dec.Decode(dst); err != nil {
		return err
	}
	var extra json.RawMessage
	if err := dec.Decode(&extra); err != io.EOF {
		if err == nil {
			return fmt.Errorf("trailing JSON value")
		}
		return fmt.Errorf("trailing JSON value: %w", err)
	}
	return nil
}
`)
	return b.String(), nil
}

func indexOf(ops []*shape, name string) int {
	for i, op := range ops {
		if op.Name == name {
			return i
		}
	}
	return -1
}

func (g *generator) serviceOps() []*shape {
	out := make([]*shape, 0, len(g.m.Service.Operations))
	for _, id := range g.m.Service.Operations {
		out = append(out, g.m.shape(id))
	}
	return out
}

func (g *generator) writeOpLiteral(b *strings.Builder, op *shape) {
	fmt.Fprintf(b, "\t{Name: %q, Target: %q, Input: %q, Output: %q, Idempotent: %t",
		op.Name, g.m.Service.Name+"."+op.Name, g.m.shape(op.Input).Name, g.m.shape(op.Output).Name, op.Traits.Idempotent)
	if len(op.Errors) > 0 {
		b.WriteString(", Errors: []string{")
		for i, id := range op.Errors {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(b, "%q", g.m.shape(id).Name)
		}
		b.WriteString("}")
	}
	if p := op.Traits.Paginated; p != nil {
		fmt.Fprintf(b, ", InputToken: %q, OutputToken: %q, PageItems: %q, PageSize: %q", p.InputToken, p.OutputToken, p.Items, p.PageSize)
	}
	b.WriteString("},\n")
}

func (g *generator) errorsFile() (string, error) {
	var b strings.Builder
	b.WriteString(g.header())
	b.WriteString(`// APIError is a modeled service error.
type APIError interface {
	error
	ShapeID() string
	ErrorName() string
	StatusCode() int
}

`)
	errs := g.sortedErrors()
	for _, sh := range errs {
		fmt.Fprintf(&b, "func (e *%s) Error() string {\n", sh.Name)
		b.WriteString("\tif e == nil || e.Message == nil {\n")
		fmt.Fprintf(&b, "\t\treturn %q\n\t}\n", sh.Name)
		fmt.Fprintf(&b, "\treturn %q + *e.Message\n}\n\n", sh.Name+": ")
		fmt.Fprintf(&b, "func (e *%s) ShapeID() string { return %q }\n\n", sh.Name, sh.ID)
		fmt.Fprintf(&b, "func (e *%s) ErrorName() string { return %q }\n\n", sh.Name, sh.Name)
		fmt.Fprintf(&b, "func (e *%s) StatusCode() int { return %d }\n\n", sh.Name, sh.httpStatus())
	}
	b.WriteString("// NewModeledError builds an error shape by name. The message is the Smithy message member.\nfunc NewModeledError(name, message string) (APIError, bool) {\n\tm := message\n\tswitch name {\n")
	for _, sh := range errs {
		fmt.Fprintf(&b, "\tcase %q:\n\t\treturn &%s{Message: &m}, true\n", sh.Name, sh.Name)
	}
	b.WriteString("\tdefault:\n\t\treturn nil, false\n\t}\n}\n")
	return b.String(), nil
}

func (g *generator) sortedErrors() []*shape {
	var out []*shape
	for _, sh := range g.sorted("structure") {
		if sh.Traits.ErrorFault != "" {
			out = append(out, sh)
		}
	}
	return out
}

func (g *generator) validateFile() (string, error) {
	var methods strings.Builder
	for _, sh := range g.sorted("structure") {
		if err := g.writeValidate(&methods, sh); err != nil {
			return "", err
		}
	}
	var b strings.Builder
	b.WriteString(g.header())
	imps := []string{"fmt", "strconv", "unicode/utf8"}
	if len(g.patterns) > 0 {
		imps = append(imps, "regexp")
	}
	needsSort := strings.Contains(methods.String(), "sort.Strings")
	if needsSort {
		imps = append(imps, "sort")
	}
	sort.Strings(imps)
	b.WriteString("import (\n")
	for _, imp := range imps {
		fmt.Fprintf(&b, "\t%q\n", imp)
	}
	b.WriteString(")\n\n")
	b.WriteString(validateHelpers)
	if len(g.patterns) > 0 {
		if err := g.writePatterns(&b); err != nil {
			return "", err
		}
	} else {
		b.WriteString("func matchPattern(string, string) (bool, error) { return true, nil }\n\n")
	}
	b.WriteString(methods.String())
	return b.String(), nil
}

func (g *generator) writePatterns(b *strings.Builder) error {
	b.WriteString("type patternProgram struct {\n\tre *regexp.Regexp\n\textra *regexp.Regexp\n}\n\n")
	b.WriteString("var patternPrograms = map[string]patternProgram{\n")
	keys := make([]string, 0, len(g.patterns))
	for k := range g.patterns {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		p := g.patterns[k]
		fmt.Fprintf(b, "\t%q: {re: regexp.MustCompile(%q)", k, p.main)
		if p.extra != "" {
			fmt.Fprintf(b, ", extra: regexp.MustCompile(%q)", p.extra)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\nfunc matchPattern(pattern, value string) (bool, error) {\n\tp, ok := patternPrograms[pattern]\n\tif !ok {\n\t\treturn false, fmt.Errorf(\"internal: pattern not registered\")\n\t}\n\tif !p.re.MatchString(value) {\n\t\treturn false, nil\n\t}\n\tif p.extra != nil && !p.extra.MatchString(value) {\n\t\treturn false, nil\n\t}\n\treturn true, nil\n}\n\n")
	return nil
}

func (g *generator) writeValidate(b *strings.Builder, sh *shape) error {
	fmt.Fprintf(b, "func (s *%s) Validate() error {\n\tif s == nil {\n\t\treturn requiredError(%q)\n\t}\n\treturn s.validateAt(\"\")\n}\n\n", sh.Name, sh.Name)
	fmt.Fprintf(b, "func (s *%s) validateAt(prefix string) error {\n", sh.Name)
	for _, mem := range sh.Members {
		if err := g.writeMember(b, "s."+exportName(mem.Name), fmt.Sprintf("joinPath(prefix, %q)", mem.Name), mem); err != nil {
			return fmt.Errorf("%s.%s: %w", sh.Name, mem.Name, err)
		}
	}
	b.WriteString("\treturn nil\n}\n\n")
	return nil
}

func (g *generator) writeMember(b *strings.Builder, fieldExpr, pathExpr string, mem member) error {
	sh := g.m.shape(mem.Target)
	tr := mergeTraits(sh.Traits, mem.Traits)
	needs := g.valueNeedsCheck(mem.Target, mem.Traits)
	if !tr.Required && !needs {
		return nil
	}
	if tr.Required {
		fmt.Fprintf(b, "\tif %s == nil {\n\t\treturn requiredError(%s)\n\t}\n", fieldExpr, pathExpr)
		if !needs {
			return nil
		}
		return g.writeValue(b, "*"+fieldExpr, pathExpr, mem.Target, mem.Traits, "\t")
	}
	fmt.Fprintf(b, "\tif %s != nil {\n", fieldExpr)
	if err := g.writeValue(b, "*"+fieldExpr, pathExpr, mem.Target, mem.Traits, "\t\t"); err != nil {
		return err
	}
	b.WriteString("\t}\n")
	return nil
}

func (g *generator) valueNeedsCheck(targetID string, over traits) bool {
	sh := g.m.shape(targetID)
	tr := mergeTraits(sh.Traits, over)
	switch sh.Kind {
	case "structure", "enum":
		return true
	case "string":
		return tr.HasLength || tr.HasPattern
	case "integer", "long", "float":
		return tr.HasRangeMin || tr.HasRangeMax
	case "boolean", "timestamp":
		return false
	case "list":
		if tr.HasLength {
			return true
		}
		return g.valueNeedsCheck(sh.ListOf.Target, sh.ListOf.Traits)
	case "map":
		if tr.HasLength {
			return true
		}
		return g.valueNeedsCheck(sh.MapKey.Target, sh.MapKey.Traits) || g.valueNeedsCheck(sh.MapValue.Target, sh.MapValue.Traits)
	default:
		return true
	}
}

func (g *generator) writeValue(b *strings.Builder, expr, pathExpr, targetID string, over traits, indent string) error {
	sh := g.m.shape(targetID)
	tr := mergeTraits(sh.Traits, over)
	switch sh.Kind {
	case "string":
		if err := g.notePattern(tr); err != nil {
			return err
		}
		min, max, hasMin, hasMax, err := lengthArgs(tr)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%sif err := checkString(%s, %s, %s, %s, %t, %t, %q); err != nil {\n%s\treturn err\n%s}\n",
			indent, pathExpr, expr, min, max, hasMin, hasMax, patternOrEmpty(tr), indent, indent)
	case "integer", "long":
		min, max, hasMin, hasMax, err := rangeInts(tr)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%sif err := checkInt(%s, int64(%s), %s, %s, %t, %t); err != nil {\n%s\treturn err\n%s}\n",
			indent, pathExpr, expr, min, max, hasMin, hasMax, indent, indent)
	case "float":
		min, max, hasMin, hasMax, err := rangeFloats(tr)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%sif err := checkFloat(%s, float64(%s), %s, %s, %t, %t); err != nil {\n%s\treturn err\n%s}\n",
			indent, pathExpr, expr, min, max, hasMin, hasMax, indent, indent)
	case "enum":
		fmt.Fprintf(b, "%sif !(%s).Valid() {\n%s\treturn enumError(%s, string(%s), %sValues)\n%s}\n",
			indent, expr, indent, pathExpr, expr, sh.Name, indent)
	case "structure":
		fmt.Fprintf(b, "%s{\n%s\titem := %s\n%s\tif err := item.validateAt(%s); err != nil {\n%s\t\treturn err\n%s\t}\n%s}\n",
			indent, indent, expr, indent, pathExpr, indent, indent, indent)
	case "list":
		return g.writeList(b, expr, pathExpr, sh, tr, indent)
	case "map":
		return g.writeMap(b, expr, pathExpr, sh, tr, indent)
	case "boolean", "timestamp":
		return nil
	default:
		return fmt.Errorf("unsupported shape kind %q for shape %s", sh.Kind, targetID)
	}
	return nil
}

func (g *generator) writeList(b *strings.Builder, expr, pathExpr string, sh *shape, tr traits, indent string) error {
	min, max, hasMin, hasMax, err := lengthArgs(tr)
	if err != nil {
		return err
	}
	elemNeeds := g.valueNeedsCheck(sh.ListOf.Target, sh.ListOf.Traits)
	fmt.Fprintf(b, "%s{\n", indent)
	in := indent + "\t"
	fmt.Fprintf(b, "%sp := %s\n", in, pathExpr)
	if tr.HasLength {
		fmt.Fprintf(b, "%sif err := checkLen(p, len(%s), %s, %s, %t, %t); err != nil {\n%s\treturn err\n%s}\n",
			in, expr, min, max, hasMin, hasMax, in, in)
	}
	if elemNeeds {
		fmt.Fprintf(b, "%sfor i := range %s {\n", in, expr)
		if err := g.writeValue(b, "("+expr+")[i]", "itemPath(p, i)", sh.ListOf.Target, sh.ListOf.Traits, in+"\t"); err != nil {
			return err
		}
		fmt.Fprintf(b, "%s}\n", in)
	}
	fmt.Fprintf(b, "%s}\n", indent)
	return nil
}

func (g *generator) writeMap(b *strings.Builder, expr, pathExpr string, sh *shape, tr traits, indent string) error {
	min, max, hasMin, hasMax, err := lengthArgs(tr)
	if err != nil {
		return err
	}
	keyNeeds := g.valueNeedsCheck(sh.MapKey.Target, sh.MapKey.Traits)
	valNeeds := g.valueNeedsCheck(sh.MapValue.Target, sh.MapValue.Traits)
	fmt.Fprintf(b, "%s{\n", indent)
	in := indent + "\t"
	fmt.Fprintf(b, "%sp := %s\n", in, pathExpr)
	if tr.HasLength {
		fmt.Fprintf(b, "%sif err := checkLen(p, len(%s), %s, %s, %t, %t); err != nil {\n%s\treturn err\n%s}\n",
			in, expr, min, max, hasMin, hasMax, in, in)
	}
	if keyNeeds || valNeeds {
		fmt.Fprintf(b, "%skeys := make([]string, 0, len(%s))\n", in, expr)
		fmt.Fprintf(b, "%sfor k := range %s {\n%s\tkeys = append(keys, string(k))\n%s}\n", in, expr, in, in)
		fmt.Fprintf(b, "%ssort.Strings(keys)\n", in)
		fmt.Fprintf(b, "%sfor _, ks := range keys {\n", in)
		keyType, err := g.valueType(sh.MapKey.Target)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%s\tk := %s(ks)\n", in, keyType)
		if valNeeds {
			fmt.Fprintf(b, "%s\tv := (%s)[k]\n", in, expr)
		}
		fmt.Fprintf(b, "%s\tkp := indexPath(p, ks)\n", in)
		if keyNeeds {
			if err := g.writeValue(b, "k", "kp", sh.MapKey.Target, sh.MapKey.Traits, in+"\t"); err != nil {
				return err
			}
		}
		if valNeeds {
			if err := g.writeValue(b, "v", "kp", sh.MapValue.Target, sh.MapValue.Traits, in+"\t"); err != nil {
				return err
			}
		}
		fmt.Fprintf(b, "%s}\n", in)
	}
	fmt.Fprintf(b, "%s}\n", indent)
	return nil
}

func (g *generator) notePattern(tr traits) error {
	if !tr.HasPattern {
		return nil
	}
	if _, ok := g.patterns[tr.Pattern]; ok {
		return nil
	}
	prog, err := lowerPattern(tr.Pattern)
	if err != nil {
		return err
	}
	g.patterns[tr.Pattern] = prog
	return nil
}

