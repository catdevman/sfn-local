func (g *generator) surface() ([]byte, error) {
	doc := surfaceDoc{
		Protocol:     protocolTrait,
		TargetPrefix: g.m.Service.Name,
		Service:      g.m.Service.ID,
		Version:      g.m.Service.Version,
	}
	for _, op := range g.serviceOps() {
		jo := surfaceOp{
			Name:       op.Name,
			Shape:      op.ID,
			Input:      g.m.shape(op.Input).Name,
			Output:     g.m.shape(op.Output).Name,
			Idempotent: op.Traits.Idempotent,
		}
		if p := op.Traits.Paginated; p != nil {
			jo.Pagination = p
		}
		for _, id := range op.Errors {
			jo.Errors = append(jo.Errors, g.m.shape(id).Name)
		}
		var err error
		jo.InputMembers, err = g.surfaceMembers(op.Input)
		if err != nil {
			return nil, err
		}
		jo.OutputMembers, err = g.surfaceMembers(op.Output)
		if err != nil {
			return nil, err
		}
		doc.Operations = append(doc.Operations, jo)
	}
	for _, sh := range g.sortedErrors() {
		je := surfaceError{Name: sh.Name, Shape: sh.ID, Fault: sh.Traits.ErrorFault, Status: sh.httpStatus()}
		for _, mem := range sh.Members {
			je.Members = append(je.Members, mem.Name)
		}
		doc.Errors = append(doc.Errors, je)
	}
	for _, sh := range g.sorted("enum") {
		doc.Enums = append(doc.Enums, surfaceEnum{Name: sh.Name, Values: sh.enumValues()})
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(doc); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func (g *generator) surfaceMembers(structID string) ([]surfaceMember, error) {
	sh := g.m.shape(structID)
	out := make([]surfaceMember, 0, len(sh.Members))
	for _, mem := range sh.Members {
		target := g.m.shape(mem.Target)
		tr := mergeTraits(target.Traits, mem.Traits)
		sm := surfaceMember{
			Name:             mem.Name,
			Target:           target.Name,
			Kind:             target.Kind,
			Required:         tr.Required,
			Sensitive:        tr.Sensitive,
			IdempotencyToken: tr.IdempotencyToken,
		}
		if tr.HasDefault {
			sm.HasDefault = true
			sm.Default = tr.Default
		}
		if tr.HasLength {
			sm.Length = &surfaceLength{Min: tr.LengthMin, Max: tr.LengthMax}
		}
		if tr.HasPattern {
			sm.Pattern = tr.Pattern
		}
		if tr.HasRangeMin || tr.HasRangeMax {
			rg := &surfaceRange{}
			if tr.HasRangeMin {
				rg.Min = json.RawMessage(tr.RangeMin)
			}
			if tr.HasRangeMax {
				rg.Max = json.RawMessage(tr.RangeMax)
			}
			sm.Range = rg
		}
		if target.Kind == "enum" {
			sm.Enum = target.enumValues()
		}
		out = append(out, sm)
	}
	return out, nil
}

