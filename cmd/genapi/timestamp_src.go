package main

// timestampSrc is written to timestamp.go on every run. It does not depend
// on the model. Epoch seconds stay a plain JSON number, including a fraction.
const timestampSrc = `// Code generated by cmd/genapi. DO NOT EDIT.

package gen

import (
	"bytes"
	"fmt"
	"strconv"
	"strings"
)

// Timestamp is a Smithy timestamp encoded as epoch seconds.
// A fractional part is legal. Scientific notation is rejected on input
// and is never written.
type Timestamp struct {
	seconds float64
	literal string
}

// NewTimestamp returns a timestamp at the given epoch seconds.
func NewTimestamp(seconds float64) Timestamp {
	return Timestamp{seconds: seconds}
}

// Seconds returns the epoch seconds.
func (t Timestamp) Seconds() float64 { return t.seconds }

// MarshalJSON writes a plain decimal number.
func (t Timestamp) MarshalJSON() ([]byte, error) {
	if t.literal != "" {
		if v, err := strconv.ParseFloat(t.literal, 64); err == nil && v == t.seconds {
			return []byte(t.literal), nil
		}
	}
	s := strconv.FormatFloat(t.seconds, 'f', -1, 64)
	if strings.ContainsAny(s, "eE") {
		return nil, fmt.Errorf("timestamp %s would use scientific notation", s)
	}
	return []byte(s), nil
}

// UnmarshalJSON accepts a plain JSON number.
func (t *Timestamp) UnmarshalJSON(data []byte) error {
	data = bytes.TrimSpace(data)
	if !plainNumber(data) {
		return fmt.Errorf("timestamp must be a plain JSON number")
	}
	v, err := strconv.ParseFloat(string(data), 64)
	if err != nil {
		return fmt.Errorf("timestamp: %w", err)
	}
	t.seconds = v
	t.literal = string(data)
	return nil
}

func plainNumber(b []byte) bool {
	if len(b) == 0 {
		return false
	}
	i := 0
	if b[0] == '-' {
		i++
		if i >= len(b) {
			return false
		}
	}
	if b[i] == '0' {
		i++
	} else if b[i] >= '1' && b[i] <= '9' {
		for i < len(b) && b[i] >= '0' && b[i] <= '9' {
			i++
		}
	} else {
		return false
	}
	if i < len(b) && b[i] == '.' {
		i++
		start := i
		for i < len(b) && b[i] >= '0' && b[i] <= '9' {
			i++
		}
		if i == start {
			return false
		}
	}
	return i == len(b)
}
`
