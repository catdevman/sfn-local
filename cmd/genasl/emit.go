package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

func emit(doc *document, outDir, sourceName string) error {
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}
	src, err := goSource(doc, sourceName)
	if err != nil {
		return err
	}
	formatted, err := format.Source([]byte(src))
	if err != nil {
		path := filepath.Join(os.TempDir(), "genasl-matrix.go")
		_ = os.WriteFile(path, []byte(src), 0o644)
		return fmt.Errorf("matrix.go: %w (unformatted source at %s)", err, path)
	}
	if !bytes.HasSuffix(formatted, []byte("\n")) {
		formatted = append(formatted, '\n')
	}
	if err := os.WriteFile(filepath.Join(outDir, "matrix.go"), formatted, 0o644); err != nil {
		return err
	}
	raw, err := jsonSource(doc)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(outDir, "matrix.json"), raw, 0o644)
}

func goSource(doc *document, sourceName string) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by cmd/genasl from %s. DO NOT EDIT.\n\npackage specgen\n\n", sourceName)
	b.WriteString(`// Presence is how a common field applies to one state type.
type Presence string

const (
	PresenceRequired Presence = "required"
	PresenceAllowed  Presence = "allowed"
	PresenceAbsent   Presence = "absent"
)

// StateCells is one field's presence on each state type, in spec column order.
type StateCells struct {
	Task     Presence ` + "`json:\"Task\"`" + `
	Parallel Presence ` + "`json:\"Parallel\"`" + `
	Map      Presence ` + "`json:\"Map\"`" + `
	Pass     Presence ` + "`json:\"Pass\"`" + `
	Wait     Presence ` + "`json:\"Wait\"`" + `
	Choice   Presence ` + "`json:\"Choice\"`" + `
	Succeed  Presence ` + "`json:\"Succeed\"`" + `
	Fail     Presence ` + "`json:\"Fail\"`" + `
}

// Field is one single-identifier row from a state-type table.
type Field struct {
	Name   string     ` + "`json:\"name\"`" + `
	States StateCells ` + "`json:\"states\"`" + `
}

// Note is a prose row such as "One of: Next or End". It is not a field.
type Note struct {
	Text   string     ` + "`json:\"text\"`" + `
	States StateCells ` + "`json:\"states\"`" + `
}

// Language is the JSONata table or the JSONPath table.
type Language struct {
	Name   string  ` + "`json:\"name\"`" + `
	Fields []Field ` + "`json:\"fields\"`" + `
	Notes  []Note  ` + "`json:\"notes\"`" + `
}

`)
	b.WriteString("var Languages = []Language{\n")
	for _, lang := range doc.Languages {
		fmt.Fprintf(&b, "\t{Name: %q, Fields: []Field{\n", lang.Name)
		for _, f := range lang.Fields {
			fmt.Fprintf(&b, "\t\t{Name: %q, States: %s},\n", f.Name, cellsLit(f.States))
		}
		b.WriteString("\t}, Notes: []Note{\n")
		for _, n := range lang.Notes {
			fmt.Fprintf(&b, "\t\t{Text: %q, States: %s},\n", n.Text, cellsLit(n.States))
		}
		b.WriteString("\t}},\n")
	}
	b.WriteString("}\n\n")
	writeStrings(&b, "AppendixA", doc.AppendixA)
	writeStrings(&b, "AppendixB", doc.AppendixB)
	return b.String(), nil
}

func cellsLit(c stateCells) string {
	return fmt.Sprintf("StateCells{Task: %q, Parallel: %q, Map: %q, Pass: %q, Wait: %q, Choice: %q, Succeed: %q, Fail: %q}",
		c.Task, c.Parallel, c.Map, c.Pass, c.Wait, c.Choice, c.Succeed, c.Fail)
}

func writeStrings(b *strings.Builder, name string, vals []string) {
	fmt.Fprintf(b, "var %s = []string{\n", name)
	for _, v := range vals {
		fmt.Fprintf(b, "\t%q,\n", v)
	}
	b.WriteString("}\n\n")
}

func jsonSource(doc *document) ([]byte, error) {
	type jCells struct {
		Task     string `json:"Task"`
		Parallel string `json:"Parallel"`
		Map      string `json:"Map"`
		Pass     string `json:"Pass"`
		Wait     string `json:"Wait"`
		Choice   string `json:"Choice"`
		Succeed  string `json:"Succeed"`
		Fail     string `json:"Fail"`
	}
	type jField struct {
		Name   string `json:"name"`
		States jCells `json:"states"`
	}
	type jNote struct {
		Text   string `json:"text"`
		States jCells `json:"states"`
	}
	type jLang struct {
		Name   string   `json:"name"`
		Fields []jField `json:"fields"`
		Notes  []jNote  `json:"notes"`
	}
	out := struct {
		Languages []jLang  `json:"languages"`
		AppendixA []string `json:"appendixA"`
		AppendixB []string `json:"appendixB"`
	}{AppendixA: doc.AppendixA, AppendixB: doc.AppendixB}
	conv := func(c stateCells) jCells {
		return jCells{c.Task, c.Parallel, c.Map, c.Pass, c.Wait, c.Choice, c.Succeed, c.Fail}
	}
	for _, lang := range doc.Languages {
		jl := jLang{Name: lang.Name}
		for _, f := range lang.Fields {
			jl.Fields = append(jl.Fields, jField{Name: f.Name, States: conv(f.States)})
		}
		for _, n := range lang.Notes {
			jl.Notes = append(jl.Notes, jNote{Text: n.Text, States: conv(n.States)})
		}
		out.Languages = append(out.Languages, jl)
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(out); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
